/* Single-line ink illustrations, hand-authored. Every stroke has pathLength=1 and draws itself from one
   CSS variable on its <svg>: --k (0→1). Each stroke has its own window [s,e] inside that progress.
   Ported from docs/v4/proto2/js/ink.js — paths and timings unchanged. */

export interface InkPath {
  d: string;
  s: number;
  e: number;
  c: string;
}

export const P = (d: string, s = 0, e = 1, c = ""): InkPath => ({ d, s, e, c });

export const svg = (vb: string, paths: InkPath[], extra = "", cls = ""): string => {
  const w = +vb.split(" ")[2];
  const g = Math.max(1, w / 120);
  return `<svg class="ill ${cls}" viewBox="${vb}" style="--sw:${Math.max(1.8, w / 90).toFixed(2)}" aria-hidden="true">${paths
    .map(
      (p, i) =>
        `<path class="ink ${p.c}" pathLength="1" d="${p.d}" style="--s:${p.s};--e:${p.e}"/><path class="ink ghost ${p.c}" pathLength="1" d="${p.d}" transform="translate(${(i % 2 ? 0.9 : -0.7) * g} ${(i % 3 ? 0.6 : -0.8) * g})" style="--s:${Math.min(0.98, p.s + 0.04)};--e:${Math.min(1, p.e + 0.04)}"/>`,
    )
    .join("")}${extra}</svg>`;
};

